#!/usr/bin/env python3
"""Render the compatibility probe matrix; --check detects stale documentation.

Uses only the Python standard library. This never runs jpx, fetches specifications,
or updates expected results: behavior changes require a reviewed fixture edit.
"""

import argparse
import html
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "crates/jpx/tests/fixtures/compatibility_audit/cases.json"
DOCUMENT = ROOT / "docs/src/configuration/compatibility-audit.md"


def code(text):
    # Pipes delimit Markdown tables even inside code spans. HTML also handles
    # expressions that themselves contain backticks, angle brackets or '&'.
    return "<code>" + html.escape(text).replace("|", "&#124;") + "</code>"


def outcome(expected):
    if expected["kind"] == "value":
        return code(json.dumps(expected["value"], ensure_ascii=False, separators=(",", ":")))
    return "error: " + code(expected["error"])


def comparable(expected):
    """Exclude provenance and diagnostic wording from spec comparisons."""
    if expected["kind"] == "value":
        return ("value", json.dumps(expected["value"], sort_keys=True))
    return ("error", expected["error"])


def render(audit):
    original = audit["original_compliance"]
    community = audit["community_spec"]
    sources = audit["sources"]
    rows = audit["cases"]
    lines = [
        "<!-- Generated by scripts/generate_compatibility_audit.py; edit fixtures or the generator. -->",
        "# Compatibility audit: current behavior probes",
        "",
        f"This first milestone for #235 records **{len(rows)} limited probes**, not complete",
        "original JMESPath or JMESPath Community conformance. It preserves current",
        "behavior, including known differences. A passing test means jpx still matches",
        "the recorded observations; it does not mean every spec expectation is met.",
        "",
        "The machine-readable source of every row is",
        "[cases.json](https://github.com/joshrotenberg/jpx/blob/main/crates/jpx/tests/fixtures/compatibility_audit/cases.json).",
        "It records the exact input, expression, original/Community expectation, source,",
        "shared-parser outcome, default/strict evaluation, and focused error diagnostics.",
        "The test also checks CLI exit status (0 for values, 1 for errors), stderr, and",
        "JSON output. CLI null results produce no stdout; the engine test checks the",
        "actual null value independently. Error labels in this audit are classifications",
        "for these probes, not a new runtime error API. In particular, jpx currently",
        "reports an undefined lexical variable using an unknown-function diagnostic.",
        "",
        "## Reference baseline",
        "",
        "- Original: [published specification](https://jmespath.org/specification.html),",
        f"  plus the existing [original compliance fixtures]({original['url']}) at",
        f"  `{original['commit']}`. Rows marked with fixture coordinates are",
        "  checked against the vendored input, expression, and expectation; those files",
        "  are not modified. Other rows are locally authored probes based on the spec.",
        "  Function expectations assume the original standard function set, without",
        "  custom extension registrations.",
        f"- Community: [pinned specification repository]({community['url']}) at",
        f"  `{community['commit']}`. Row sources link to that commit,",
        "  including accepted JEPs. The pinned snapshot was inspected locally;",
        "  reproduction does not require that checkout or network access.",
        f"- [Community published specification]({community['published_url']}) is a",
        "  moving publication link, not the reproducibility pin. The pinned consolidated",
        "  `GRAMMAR.ABNF` does not yet contain ternary syntax; the ternary expectation",
        "  here comes specifically from accepted Community JEP-21. This audit does not",
        "  silently equate proposals, the consolidated grammar, and the published site.",
        "",
        "Original JEP-18 is the **lexical-scope proposal**, tracked by accepted Community",
        "JEP-11a. It is not part of the original published grammar used as this baseline.",
        "Community JEP-18 instead adds **group_by**. Community JEP-16 adds arithmetic,",
        "JEP-17 adds root `$`, JEP-19 clarifies pipe/null evaluation, and JEP-21 adds",
        "ternary conditionals. Parenthesized grouping is separate from `group_by`.",
        "See the pinned [lexical-scope cross-reference][community-let] and",
        "[grouping proposal][community-grouping] for the numbering distinction.",
        "",
        "## Grammar, function restrictions, and build features",
        "",
        "The shared-parser column is tested with both a runtime containing extensions",
        "and `Runtime::strict()`. Function registration does not select a different",
        "parser. The default/strict columns are each tested through `JpxEngine` and the",
        "CLI (`--strict` for the latter); CLI cases use isolated child configuration.",
        "Strict policy removes extension functions and rejects let AST nodes after",
        "parsing. It does not guarantee a separate original-only grammar: the bare",
        "`let` identifier failure in both modes is one observable consequence.",
        "",
        "`jpx-core` enables `let-expr` by default. Normal CLI dependency resolution",
        "therefore enables it even though the CLI's own default feature list is empty.",
        "The test asserts actual runtime let support and never skips let rows based on",
        "`cfg!(feature = \"let-expr\")` in the CLI crate. Adding `--features let-expr`",
        "explicitly should produce the same matrix. `--no-default-features -p jpx`",
        "alone does not disable a dependency's default features. Embedders building",
        "core without its default features must opt into `let-expr`; that separate",
        "build is not represented by the default/strict columns. The core feature-off",
        "lexer check below is only a build-gate probe, not a second conformance matrix.",
        "",
        "## Reproduce",
        "",
        "From the repository root, with the locked Cargo dependencies cached:",
        "",
        "```bash",
        "cargo test --offline -p jpx --test compatibility_audit",
        "cargo test --offline -p jpx --features let-expr --test compatibility_audit",
        "cargo test --offline -p jpx-core --no-default-features --lib lexer::tests::ensures_eq_invalid_without_let_expr -- --exact",
        "cargo test --offline -p jpx-core --test compliance",
        "python3 scripts/generate_compatibility_audit.py --check",
        "```",
        "",
        "The audit test asserts parser acceptance separately from evaluation, checks",
        "values as JSON, and requires specific error substrings instead of accepting",
        "any failure. It does not execute another JMESPath implementation as an oracle.",
        "The original compliance suite is a separate, broader baseline; these selected",
        "CLI/engine probes do not replace it. No Community compliance suite is vendored",
        "or executed in this milestone.",
        "",
        "After a reviewed fixture change, regenerate the document with:",
        "",
        "```bash",
        "python3 scripts/generate_compatibility_audit.py",
        "```",
        "",
        "The generator never updates observations from a running binary. `--check`",
        "fails on documentation drift and tells the caller how to regenerate it.",
        "",
        "## Matrix",
        "",
        "Every row is a probe. Inputs are in the fixture. `syntax` means a grammar",
        "rejection; `unknown-function` means function-call grammar was accepted but",
        "the function was unavailable. `strict-policy` means a parsed let expression",
        "was rejected by strict evaluation policy. Value cells show JSON, so `null`",
        "and the string `\"null\"` are different results.",
        "",
    ]
    for area in dict.fromkeys(row["area"] for row in rows):
        lines += [f"### {area.capitalize()}", "",
                  "| Probe | Expression | Original expectation | Community expectation | Shared parser | jpx default | jpx strict |",
                  "|---|---|---|---|---|---|---|"]
        section = [row for row in rows if row["area"] == area]
        for row in section:
            cells = [code(row["id"]), code(row["expression"]),
                     outcome(row["original"]) + f" [source][{row['original']['source']}]",
                     outcome(row["community"]) + f" [source][{row['community']['source']}]",
                     "accept" if row["jpx"]["parse"]["accepted"] else "reject",
                     outcome(row["jpx"]["default"]), outcome(row["jpx"]["strict"])]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
        for row in section:
            note = f"- {code(row['id'])}: {row['note']}"
            if ref := row.get("original_fixture"):
                note += (f" Original fixture `{ref['file']}`, group {ref['group']},"
                         f" case {ref['case']} (zero-based).")
            lines.append(note)
        lines.append("")
    lines += ["## Differences recorded by these probes", "",
              "This list is derived from the fixture expectations, not a support score.",
              "It includes differences in rejection phase/class: strict-policy and original",
              "syntax errors both reject let expressions, but at different stages.", ""]
    for mode in ("default", "strict"):
        for spec in ("original", "community"):
            differences = [code(row["id"]) for row in rows
                           if comparable(row["jpx"][mode]) != comparable(row[spec])]
            lines.append(f"- {mode.capitalize()} versus {spec}: " + ", ".join(differences) + ".")
    lines += ["", "## Remaining work for #235", "",
              "- Design a canonical capability registry that separates grammar, evaluation",
              "  semantics, function availability/signatures, strict policy, and build",
              "  features. Decide versioned original/Community identifiers and a single",
              "  source of truth before connecting consumers. This fixture is not that API.",
              "- Audit the exhaustive grammar and operator precedence/associativity,",
              "  arithmetic types/errors, Unicode operators, ternary truthiness and lazy",
              "  branches, root/current/lexical scope, contextual keywords, escaping,",
              "  identifier collisions, slices, and every projection/null context.",
              "- Pin and integrate the Community compliance corpus, resolve discrepancies",
              "  between accepted JEPs and consolidated/published specs, and expand original",
              "  compliance coverage across strict/default and core feature configurations.",
              "- Audit all standard and extension function signatures, error classes,",
              "  evaluation order, aliases and overrides; verify CLI, engine, MCP and Python",
              "  parity and configuration paths. Representative probes do not establish this.",
              "- Decide and implement any behavior changes separately, then update reviewed",
              "  expectations. No new syntax, modes, registry APIs, `engine_info` fields,",
              "  MCP metadata, dependencies or runtime changes are introduced here.", ""]
    lines += [f"[{name}]: {url}" for name, url in sources.items()]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the matrix is stale")
    args = parser.parse_args()
    audit = json.loads(FIXTURE.read_text(encoding="utf-8"))
    if audit["schema_version"] != 1:
        parser.error("Unsupported fixture schema; update this generator for the fixture version.")
    rendered = render(audit)
    if args.check:
        if not DOCUMENT.exists() or DOCUMENT.read_text(encoding="utf-8") != rendered:
            parser.exit(1, "Compatibility matrix is stale. Run: python3 scripts/generate_compatibility_audit.py\n")
        print(f"Compatibility matrix is current ({len(audit['cases'])} probes).")
    else:
        DOCUMENT.write_text(rendered, encoding="utf-8")
        print(f"Wrote {DOCUMENT.relative_to(ROOT)} ({len(audit['cases'])} probes).")


if __name__ == "__main__":
    main()
